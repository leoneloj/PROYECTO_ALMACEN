    private void JTABLE_Mant_almacenMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JTABLE_Mant_almacenMouseClicked
       int filaSeleccionada = JTABLE_Mant_almacen.getSelectedRow();
        if (filaSeleccionada >= 0) {
            String codigo = JTABLE_Mant_almacen.getValueAt(filaSeleccionada, 0).toString();
            int idSucursal = Integer.parseInt(JTABLE_Mant_almacen.getValueAt(filaSeleccionada, 1).toString());
            String nombre = JTABLE_Mant_almacen.getValueAt(filaSeleccionada, 3) != null ? JTABLE_Mant_almacen.getValueAt(filaSeleccionada, 3).toString() : "";
            String ubicacion = JTABLE_Mant_almacen.getValueAt(filaSeleccionada, 4) != null ? JTABLE_Mant_almacen.getValueAt(filaSeleccionada, 4).toString() : "";

            txtcodigo_almacen2.setText(codigo);
            txtnombre_almacen.setText(nombre);
            txtubicacion1.setText(ubicacion);

            // Seleccionar en el JComboBox la sucursal correspondiente por ID
            for (int i = 0; i < jComboBox1_sucursal.getItemCount(); i++) {
                String item = jComboBox1_sucursal.getItemAt(i);
                if (item.startsWith(idSucursal + " - ")) {
                    jComboBox1_sucursal.setSelectedIndex(i);
                    break;
                }
            }

            BTN_Modificar.setEnabled(true);
            BTN_Dardebaja.setEnabled(true);
            BTN_Guardar.setEnabled(false);
        }
    }//GEN-LAST:event_JTABLE_Mant_almacenMouseClicked

