public void MostrarAlmacenes() {
        JTABLE_Mant_almacen.setAutoCreateRowSorter(true);
        modeloTablaAlmacen.setRowCount(0);
        try {
            ResultSet rs = conexionBD.listarAlmacenes();
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_almacen"),
                    rs.getInt("id_sucursal"),
                    rs.getString("nombre_sucursal"),
                    rs.getString("nombre_almacen"),
                    rs.getString("ubicacion")
                };
                modeloTablaAlmacen.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al mostrar Almacenes:\n" + e.getMessage(),
                    "Error de consulta", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void buscarAlmacenes() {
        modeloTablaAlmacen.setRowCount(0);
        String busqueda = TXT_BuscarAlmacen.getText().trim();
        try {
            ResultSet rs = conexionBD.buscarAlmacenes(busqueda);
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_almacen"),
                    rs.getInt("id_sucursal"),
                    rs.getString("nombre_sucursal"),
                    rs.getString("nombre_almacen"),
                    rs.getString("ubicacion")
                };
                modeloTablaAlmacen.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null,
                    "Error al buscar Almacenes:\n" + e.getMessage(),
                    "Error de búsqueda", JOptionPane.ERROR_MESSAGE);
        }
    }
