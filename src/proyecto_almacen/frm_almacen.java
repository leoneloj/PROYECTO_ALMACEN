    /* Método para llenar el JComboBox con las sucursales */
    private void cargarSucursales() {
        jComboBox1_sucursal.removeAllItems();
        jComboBox1_sucursal.addItem("-- Seleccionar --");
        try {
            String sql = "SELECT id_sucursal, nombre FROM sucursal";
            Statement st = conexionBD.getConnection().createStatement();
            ResultSet rs = st.executeQuery(sql);
            while (rs.next()) {
                jComboBox1_sucursal.addItem(rs.getInt("id_sucursal") + " - " + rs.getString("nombre"));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al cargar sucursales:\n" + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /* Método auxiliar para obtener el ID de la sucursal seleccionada en el ComboBox */
    private int obtenerIdSucursalSeleccionada() {
        if (jComboBox1_sucursal.getSelectedIndex() <= 0) {
            return 0;
        }
        String item = jComboBox1_sucursal.getSelectedItem().toString();
        String[] partes = item.split(" - ");
        return Integer.parseInt(partes[0]);
    }

