            String correo = JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 4) != null ? JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 4).toString() : "";
            String direccion = JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 5) != null ? JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 5).toString() : "";

            txtcodigoproveedor1.setText(codigo);
            txtruc.setText(ruc);
            txtnombreproveedor1.setText(nombre);
            txt_telefono.setText(telefono);
            txtcorreo.setText(correo);
            txtdireccion.setText(direccion);

            txtnombreproveedor1.setEnabled(true);
            BTN_Modificar.setEnabled(true);
            BTN_Guardar.setEnabled(false);
