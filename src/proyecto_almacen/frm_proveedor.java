            String codigo = JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 0).toString();
            String ruc = JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 1) != null ? JTABLE_Mant_Proveedor.getValueAt(filaSeleccionada, 1).toString() : "";
