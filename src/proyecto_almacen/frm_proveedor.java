    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed
String ruc = txtruc.getText().trim();
        String nombre = txtnombreproveedor1.getText().trim();
        String telefono = txt_telefono.getText().trim();
        String correo = txtcorreo.getText().trim();
        String direccion = txtdireccion.getText().trim();

        if (ruc.isEmpty() || nombre.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Por favor, complete al menos el RUC y el Nombre del Proveedor",
                    "Campo requerido", JOptionPane.WARNING_MESSAGE);
            txtruc.requestFocus();
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(null,
                "¿Desea guardar el registro del Proveedor?", "Confirmación", JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {
            try {
                conexionBD.insertarProveedor(ruc, nombre, telefono, correo, direccion);

                JOptionPane.showMessageDialog(null, "Proveedor registrado correctamente",
                        "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);

                this.MostrarProveedores();

                txtcodigoproveedor1.setText("");
                txtruc.setText("");
                txtnombreproveedor1.setText("");
                txt_telefono.setText("");
                txtcorreo.setText("");
                txtdireccion.setText("");
                BTN_Guardar.setEnabled(false);

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "Error al registrar Proveedor:\n"
                        + ex.getMessage(), "Error de base de datos", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

    private void BTN_ModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_ModificarActionPerformed
String codStr = txtcodigoproveedor1.getText().trim();
        String ruc = txtruc.getText().trim();
        String nombre = txtnombreproveedor1.getText().trim();
        String telefono = txt_telefono.getText().trim();
        String correo = txtcorreo.getText().trim();
        String direccion = txtdireccion.getText().trim();

        if (codStr.isEmpty() || ruc.isEmpty() || nombre.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Seleccione un proveedor de la tabla y complete el RUC y Nombre",
                    "Campo requerido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int codigo = Integer.parseInt(codStr);

        int respuesta = JOptionPane.showConfirmDialog(null,
                "¿Desea modificar este proveedor?", "Confirmación",
                JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {
            try {
                conexionBD.modificarProveedor(codigo, ruc, nombre, telefono, correo, direccion);

                JOptionPane.showMessageDialog(null, "Proveedor modificado correctamente",
                        "Modificación exitosa", JOptionPane.INFORMATION_MESSAGE);

                this.MostrarProveedores();

                txtcodigoproveedor1.setText("");
                txtruc.setText("");
                txtnombreproveedor1.setText("");
                txt_telefono.setText("");
                txtcorreo.setText("");
                txtdireccion.setText("");
                BTN_Modificar.setEnabled(false);

            } catch (Exception ex) {
                JOptionPane.showMessageDialog(null, "Error al modificar proveedor:\n"
                        + ex.getMessage(), "Error de base de datos", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_BTN_ModificarActionPerformed

