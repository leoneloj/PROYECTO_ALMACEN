public void MostrarProveedores() {
        txtnombreproveedor1.setEnabled(true);
        JTABLE_Mant_Proveedor.setAutoCreateRowSorter(true);
        modeloTablaProveedor.setRowCount(0);
        try {
            ResultSet rs = conexionBD.listarProveedores();
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_proveedor"),
                    rs.getString("ruc"),
                    rs.getString("nombre"),
                    rs.getString("telefono"),
                    rs.getString("correo"),
                    rs.getString("direccion")
                };
                modeloTablaProveedor.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al mostrar Proveedor:\n" + e.getMessage(),
                    "Error de consulta", JOptionPane.ERROR_MESSAGE);
        }
    }
public void buscarProveedores() {
        modeloTablaProveedor.setRowCount(0);
        String busqueda = TXT_BuscarProveedor.getText().trim();
        try {
            ResultSet rs = conexionBD.buscarProveedores(busqueda);
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_proveedor"),
                    rs.getString("ruc"),
                    rs.getString("nombre"),
                    rs.getString("telefono"),
                    rs.getString("correo"),
                    rs.getString("direccion")
                };
                modeloTablaProveedor.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null,
                    "Error al buscar Proveedores:\n" + e.getMessage(),
                    "Error de búsqueda", JOptionPane.ERROR_MESSAGE);
        }
    }
