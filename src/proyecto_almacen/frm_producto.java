    /* Método para llenar el JComboBox con las subcategorías */
    private void cargarSubcategorias() {
        jComboBox_Subcategoria.removeAllItems();
        jComboBox_Subcategoria.addItem("-- Seleccionar --");
        try {
            String sql = "SELECT id_subcategoria, nombre_subcategoria FROM subcategoria";
            Statement st = conexionBD.getConnection().createStatement();
            ResultSet rs = st.executeQuery(sql);
            while (rs.next()) {
                jComboBox_Subcategoria.addItem(rs.getInt("id_subcategoria") + " - " + rs.getString("nombre_subcategoria"));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al cargar subcategorías:\n" + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /* Método auxiliar para obtener el ID de la subcategoría seleccionada en el ComboBox */
    private int obtenerIdSubcategoriaSeleccionada() {
        if (jComboBox_Subcategoria.getSelectedIndex() <= 0) {
            return 0;
        }
        String item = jComboBox_Subcategoria.getSelectedItem().toString();
        String[] partes = item.split(" - ");
        return Integer.parseInt(partes[0]);
    }

