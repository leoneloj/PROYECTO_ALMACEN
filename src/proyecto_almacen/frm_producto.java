public void MostrarProductos() {
        txt_nombreproducto1.setEnabled(true);
        JTABLE_Mant_producto.setAutoCreateRowSorter(true);
        modeloTablaProducto.setRowCount(0);
        try {
            ResultSet rs = conexionBD.listarProductos();
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_producto"),
                    rs.getInt("id_subcategoria"),
                    rs.getString("nombre_subcategoria"),
                    rs.getString("codigo"),
                    rs.getString("nombre_producto"),
                    rs.getDouble("precio_venta"),
                    rs.getString("unidad_medida")
                };
                modeloTablaProducto.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al mostrar Productos:\n" + e.getMessage(),
                    "Error de consulta", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void buscarProductos() {
        modeloTablaProducto.setRowCount(0);
        String busqueda = TXT_BuscarProducto.getText().trim();
        try {
            ResultSet rs = conexionBD.buscarProductos(busqueda);
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_producto"),
                    rs.getInt("id_subcategoria"),
                    rs.getString("nombre_subcategoria"),
                    rs.getString("codigo"),
                    rs.getString("nombre_producto"),
                    rs.getDouble("precio_venta"),
                    rs.getString("unidad_medida")
                };
                modeloTablaProducto.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null,
                    "Error al buscar Productos:\n" + e.getMessage(),
                    "Error de búsqueda", JOptionPane.ERROR_MESSAGE);
        }
    }
