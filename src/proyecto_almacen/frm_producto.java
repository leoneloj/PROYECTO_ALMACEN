            String unidad = JTABLE_Mant_producto.getValueAt(filaSeleccionada, 6) != null ? JTABLE_Mant_producto.getValueAt(filaSeleccionada, 6).toString() : "";

            txt_idproducto1.setText(id);
            txt_codigoproducto.setText(codigo);
            txt_nombreproducto1.setText(nombre);
            txt_PrecioVenta1.setText(precio);
            txt_unidadmedida.setText(unidad);

            // Seleccionar en el JComboBox la subcategoría correspondiente por ID
            for (int i = 0; i < jComboBox_Subcategoria.getItemCount(); i++) {
                String item = jComboBox_Subcategoria.getItemAt(i);
                if (item.startsWith(idSubcategoria + " - ")) {
                    jComboBox_Subcategoria.setSelectedIndex(i);
                    break;
                }
            }

