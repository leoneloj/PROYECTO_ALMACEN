    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed
        int idSubcategoria = obtenerIdSubcategoriaSeleccionada();
        String codigo = txt_codigoproducto.getText().trim();
        String nombre = txt_nombreproducto1.getText().trim();
        String precioStr = txt_PrecioVenta1.getText().trim();
        String unidad = txt_unidadmedida.getText().trim();

        if (idSubcategoria == 0 || codigo.isEmpty() || nombre.isEmpty() || precioStr.isEmpty() || unidad.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Por favor, complete todos los campos requeridos.",
                    "Campo requerido", JOptionPane.WARNING_MESSAGE);
            return;
        }

        double precio = 0;
        try {
            precio = Double.parseDouble(precioStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Ingrese un precio de venta válido.",
                    "Validación", JOptionPane.WARNING_MESSAGE);
            txt_PrecioVenta1.requestFocus();
            return;
        }

        int respuesta = JOptionPane.showConfirmDialog(null,
                "¿Desea guardar el registro del Producto?", "Confirmación", JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {
            try {
                conexionBD.insertarProducto(idSubcategoria, codigo, nombre, precio, unidad);

                JOptionPane.showMessageDialog(null, "Producto registrado correctamente",
                        "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);

                this.MostrarProductos();

                txt_idproducto1.setText("");
                txt_codigoproducto.setText("");
                txt_nombreproducto1.setText("");
                txt_PrecioVenta1.setText("");
                txt_unidadmedida.setText("");
                jComboBox_Subcategoria.setSelectedIndex(0);

                BTN_Guardar.setEnabled(false);

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "Error al registrar Producto:\n"
                        + ex.getMessage(), "Error de base de datos", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

