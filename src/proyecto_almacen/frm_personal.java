    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed
        if (jComboBox_personal.getSelectedIndex() == 0 || jComboBox_cargo.getSelectedIndex() == 0 ||
            jComboBox_area.getSelectedIndex() == 0 || jComboBox_sucursal.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar las opciones de Tipo Personal, Cargo, Área y Sucursal.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (txt_nombre.getText().trim().isEmpty() || txt_apellidos.getText().trim().isEmpty() || txt_documento.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idTipo = Integer.parseInt(jComboBox_personal.getSelectedItem().toString().split(" - ")[0]);
            int idCargo = Integer.parseInt(jComboBox_cargo.getSelectedItem().toString().split(" - ")[0]);
            int idArea = Integer.parseInt(jComboBox_area.getSelectedItem().toString().split(" - ")[0]);
            int idSucursal = Integer.parseInt(jComboBox_sucursal.getSelectedItem().toString().split(" - ")[0]);

            conexionBD.insertarPersonal(
                idTipo, idCargo, idArea, idSucursal,
                txt_nombre.getText().trim(),
                txt_apellidos.getText().trim(),
                txt_documento.getText().trim()
            );

            JOptionPane.showMessageDialog(this, "Personal registrado exitosamente.");
            MostrarPersonal();
            LimpiarCajas();
            BTN_Guardar.setEnabled(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

    private void BTN_ModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_ModificarActionPerformed
        if (txt_personal.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para modificar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idPersonal = Integer.parseInt(txt_personal.getText());
            int idTipo = Integer.parseInt(jComboBox_personal.getSelectedItem().toString().split(" - ")[0]);
            int idCargo = Integer.parseInt(jComboBox_cargo.getSelectedItem().toString().split(" - ")[0]);
            int idArea = Integer.parseInt(jComboBox_area.getSelectedItem().toString().split(" - ")[0]);
            int idSucursal = Integer.parseInt(jComboBox_sucursal.getSelectedItem().toString().split(" - ")[0]);

            conexionBD.modificarPersonal(
                idPersonal, idTipo, idCargo, idArea, idSucursal,
                txt_nombre.getText().trim(),
                txt_apellidos.getText().trim(),
                txt_documento.getText().trim()
            );

            JOptionPane.showMessageDialog(this, "Registro de personal modificado exitosamente.");
            MostrarPersonal();
            LimpiarCajas();
            BTN_Modificar.setEnabled(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al modificar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BTN_ModificarActionPerformed

    private void TXT_BuscarPersonalKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TXT_BuscarPersonalKeyReleased
        String filtro = TXT_BuscarPersonal.getText().trim();
        modeloTablaPersonal.setRowCount(0);
        try {
            ResultSet rs = conexionBD.buscarPersonal(filtro);
            while (rs.next()) {
                Object row[] = new Object[12];
                row[0] = rs.getInt("id_personal");
                row[1] = rs.getInt("id_tipo_personal");
                row[2] = rs.getString("nombre_tipo_personal");
                row[3] = rs.getInt("id_cargo");
                row[4] = rs.getString("nombre_cargo");
                row[5] = rs.getInt("id_area");
                row[6] = rs.getString("nombre_area");
                row[7] = rs.getInt("id_sucursal");
                row[8] = rs.getString("nombre_sucursal");
                row[9] = rs.getString("nombres");
                row[10] = rs.getString("apellidos");
                row[11] = rs.getString("documento");
                modeloTablaPersonal.addRow(row);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error en la búsqueda: " + e.getMessage());
        }
    }//GEN-LAST:event_TXT_BuscarPersonalKeyReleased

