    private void jTableman_personalMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableman_personalMouseClicked
        int fila = jTableman_personal.getSelectedRow();
        if (fila >= 0) {
            txt_personal.setText(jTableman_personal.getValueAt(fila, 0).toString());

            // Seleccionar tipo de personal
            String idTipo = jTableman_personal.getValueAt(fila, 1).toString();
            for (int i = 0; i < jComboBox_personal.getItemCount(); i++) {
                if (jComboBox_personal.getItemAt(i).startsWith(idTipo + " - ")) {
                    jComboBox_personal.setSelectedIndex(i);
                    break;
                }
            }

            // Seleccionar cargo
            String idCargo = jTableman_personal.getValueAt(fila, 3).toString();
            for (int i = 0; i < jComboBox_cargo.getItemCount(); i++) {
                if (jComboBox_cargo.getItemAt(i).startsWith(idCargo + " - ")) {
                    jComboBox_cargo.setSelectedIndex(i);
                    break;
                }
            }

            // Seleccionar área
            String idArea = jTableman_personal.getValueAt(fila, 5).toString();
            for (int i = 0; i < jComboBox_area.getItemCount(); i++) {
                if (jComboBox_area.getItemAt(i).startsWith(idArea + " - ")) {
                    jComboBox_area.setSelectedIndex(i);
                    break;
                }
            }

            // Seleccionar sucursal
            String idSucursal = jTableman_personal.getValueAt(fila, 7).toString();
            for (int i = 0; i < jComboBox_sucursal.getItemCount(); i++) {
                if (jComboBox_sucursal.getItemAt(i).startsWith(idSucursal + " - ")) {
                    jComboBox_sucursal.setSelectedIndex(i);
                    break;
                }
            }

            txt_nombre.setText(jTableman_personal.getValueAt(fila, 9).toString());
            txt_apellidos.setText(jTableman_personal.getValueAt(fila, 10).toString());
            txt_documento.setText(jTableman_personal.getValueAt(fila, 11).toString());

            BTN_Guardar.setEnabled(false);
            BTN_Modificar.setEnabled(true);
        }
    }//GEN-LAST:event_jTableman_personalMouseClicked

