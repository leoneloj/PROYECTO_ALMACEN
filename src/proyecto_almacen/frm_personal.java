    private void cargarCombos() {
        try {
            // Tipo Personal
            jComboBox_personal.removeAllItems();
            jComboBox_personal.addItem("-- Seleccionar --");
            ResultSet rsTipo = conexionBD.cargarComboTipoPersonal();
            while (rsTipo.next()) {
                jComboBox_personal.addItem(rsTipo.getInt("id_tipo_personal") + " - " + rsTipo.getString("nombre_tipo_personal"));
            }

            // Cargo
            jComboBox_cargo.removeAllItems();
            jComboBox_cargo.addItem("-- Seleccionar --");
            ResultSet rsCargo = conexionBD.cargarComboCargo();
            while (rsCargo.next()) {
                jComboBox_cargo.addItem(rsCargo.getInt("id_cargo") + " - " + rsCargo.getString("nombre_cargo"));
            }

            // Area
            jComboBox_area.removeAllItems();
            jComboBox_area.addItem("-- Seleccionar --");
            ResultSet rsArea = conexionBD.cargarComboArea();
            while (rsArea.next()) {
                jComboBox_area.addItem(rsArea.getInt("id_area") + " - " + rsArea.getString("nombre_area"));
            }

            // Sucursal
            jComboBox_sucursal.removeAllItems();
            jComboBox_sucursal.addItem("-- Seleccionar --");
            ResultSet rsSucursal = conexionBD.cargarComboSucursal();
            while (rsSucursal.next()) {
                jComboBox_sucursal.addItem(rsSucursal.getInt("id_sucursal") + " - " + rsSucursal.getString("nombre"));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar listas desplegables: " + e.getMessage());
        }
    }
    

